export function normalizeAssistantMode(value: unknown): AssistantMode {
  return value === 'RESEARCH' ? 'RESEARCH' : 'MANAGEMENT';
}

export function getAssistantSystemPrompt(mode: AssistantMode): string {
  return `${mode === 'RESEARCH' ? RESEARCH_PROMPT : MANAGEMENT_PROMPT}\n${IMAGE_CAPABILITY}\n${COMMON_RULES}`;
}
